public class Prueba1U3 {
    public static void main(String[] args) {
        
        //Variable contador
        int i = 1;
        
        //El bucle se repetirá mientras i sea menor o igual a 5
        while(i <= 5){
            
            //Muestra el valor actual de i
            System.out.println(i);
            
            //Incremento la variable
            i++;
        }
    }
}
